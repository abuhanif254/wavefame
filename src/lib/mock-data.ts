const CONNECTORS = ["Think about that.", "Every single time.", "It adds up.", "Here's why.", "Remember this.", "That's the trick."] as const;

const CAMERA_CYCLE: Record<SceneType, readonly CameraEffect[]> = {
  kinetic_text: ["punch_in_fast", "zoom_in_slow", "static"],
  motion_graphic: ["static", "zoom_in_slow", "pan_right"],
  stock_footage: ["pan_left", "pan_right", "zoom_in_slow"],
  ai_grid_panel: ["zoom_in_slow", "pan_right", "pan_left", "punch_in_fast"],
};

const SFX_CYCLE: Record<SceneType, readonly SoundEffect[]> = {
  kinetic_text: ["typewriter", "pop", "cinematic_hit"],
  motion_graphic: ["whoosh", "pop"],
  stock_footage: ["none", "whoosh"],
  ai_grid_panel: ["whoosh", "pop", "none"],
};

/**
 * Builds deterministic mock scenes: one per `SCENE_DURATION_SEC` of audio.
 * Defaults to the 20-minute demo (600 scenes).
 */
export function generateMockScenes(durationSec: number = DEFAULT_AUDIO_DURATION_SEC): SceneNode[] {
  const count = Math.max(1, Math.ceil(durationSec / SCENE_DURATION_SEC));
  const chapterSize = Math.ceil(count / CHAPTERS.length);
  const scenes: SceneNode[] = [];

  for (let i = 0; i < count; i++) {
    const chapterIndex = Math.min(Math.floor(i / chapterSize), CHAPTERS.length - 1);
    const chapter = CHAPTERS[chapterIndex];
    const k = i - chapterIndex * chapterSize;
    const pass = Math.floor(k / chapter.beats.length);
    const [spoken, onScreenText, code, imagePrompt] = chapter.beats[k % chapter.beats.length];

    const visualType = TYPE_BY_CODE[code];
    const cameras = CAMERA_CYCLE[visualType];
    const sfxs = SFX_CYCLE[visualType];
    const startTime = i * SCENE_DURATION_SEC;

    const previewUrl =
      visualType === "ai_grid_panel" || visualType === "stock_footage"
        ? `https://image.pollinations.ai/prompt/${encodeURIComponent(imagePrompt)}?width=1280&height=720&nologo=true&seed=${i * 19 + 5}`
        : makePreviewUrl(i, visualType);

    scenes.push({
      id: `scene-${i.toString().padStart(4, "0")}`,
      index: i,
      startTime,
      endTime: Math.min(startTime + SCENE_DURATION_SEC, durationSec),
      transcriptSegment: pass === 0 ? spoken : `${spoken} ${CONNECTORS[(pass - 1 + chapterIndex) % CONNECTORS.length]}`,
      onScreenText,
      visualType,
      imagePrompt: pass === 0 ? imagePrompt : `${imagePrompt}, alternate angle ${pass + 1}`,
      previewUrl,
      cameraEffect: cameras[(i + pass) % cameras.length],
      sfx: k === 0 ? "cinematic_hit" : sfxs[(i + chapterIndex) % sfxs.length],
    });
  }

  // Group ai_grid_panel scenes in sets of 4 for the 1-to-4 AI Grid Slicer
  let aiCounter = 0;
  const aiGroups: SceneNode[][] = [];
  for (const sc of scenes) {
    if (sc.visualType === "ai_grid_panel") {
      const g = Math.floor(aiCounter / 4);
      if (!aiGroups[g]) aiGroups[g] = [];
      sc.quadrantIndex = (aiCounter % 4) as 0 | 1 | 2 | 3;
      aiGroups[g].push(sc);
      aiCounter++;
    }
  }

  for (let g = 0; g < aiGroups.length; g++) {
    const group = aiGroups[g];
    const masterPrompt = `2x2 visual grid: TL: ${group[0]?.imagePrompt || "concept A"}. TR: ${group[1]?.imagePrompt || "concept B"}. BL: ${group[2]?.imagePrompt || "concept C"}. BR: ${group[3]?.imagePrompt || "concept D"}. Dark cinematic studio, 8k render.`;
    const masterUrl = `https://image.pollinations.ai/prompt/${encodeURIComponent(masterPrompt)}?width=1280&height=720&nologo=true&seed=${(g + 1) * 311}`;
    for (const sc of group) {
      sc.gridMasterPrompt = masterPrompt;
      sc.gridMasterUrl = masterUrl;
    }
  }

  return scenes;
}

